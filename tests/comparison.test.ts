import { mkdir, writeFile } from 'node:fs/promises';
import { PNG } from 'pngjs';
import { afterEach, beforeAll, expect, it, vi } from 'vitest';
import { loadConfig } from '../src/config.js';
import { loadFonts } from '../src/core/fonts.js';
import { ImageStore } from '../src/core/images.js';
import { Renderer } from '../src/core/renderer.js';
import { calculateMetricDelta, diffLines } from '../src/templates/comparison/comparison.js';
import { comparison } from '../src/templates/comparison/index.js';
import { comparisonSchema } from '../src/templates/comparison/schema.js';

let renderer: Renderer;
beforeAll(async () => {
  const config = loadConfig({ LOG_LEVEL: 'silent' });
  renderer = new Renderer(config, await loadFonts(config.fontConfig));
});
afterEach(() => vi.restoreAllMocks());
it('calculates formatted metric deltas and pairs changed lines', () => {
  expect(calculateMetricDelta('12,580', '13,024')).toEqual({ label: '+444', trend: 'up' });
  expect(calculateMetricDelta('3.20%', '4.85%')).toEqual({ label: '+1.65%', trend: 'up' });
  expect(calculateMetricDelta(328, 325)).toEqual({ label: '-3', trend: 'down' });
  expect(calculateMetricDelta(0, 0)).toEqual({ label: '0', trend: 'neutral' });
  expect(calculateMetricDelta('未知', '正常').label).toBeNull();
  expect(diffLines('a\r\nb', 'a\nc')).toEqual([
    { kind: 'same', text: 'a' },
    { kind: 'del', text: 'b', counterpart: 'c' },
    { kind: 'add', text: 'c', counterpart: 'b' },
  ]);
});
it('validates each module and rejects mismatched content and legacy render options', () => {
  expect(comparisonSchema.safeParse(comparison.mock).success).toBe(true);
  for (const module of [
    { type: 'text', before: {}, after: '' },
    { type: 'metric', items: [{ before: 1 }] },
    { type: 'entity', items: [{ name: 'a' }] },
    { type: 'image', before: { url: 'ftp://example.com/a' }, after: { url: '' } },
  ]) {
    expect(comparisonSchema.safeParse({ title: '', modules: [module] }).success).toBe(false);
  }
  expect(comparisonSchema.safeParse({ ...comparison.mock, watermark: 'legacy' }).success).toBe(false);
});
it('renders every module to real PNG and SVG and keeps images in their panes', async () => {
  const red = new PNG({ width: 60, height: 40 });
  for (let i = 0; i < red.data.length; i += 4) red.data.set([220, 30, 40, 255], i);
  const uri = 'data:image/png;base64,' + PNG.sync.write(red).toString('base64');
  vi.spyOn(ImageStore.prototype, 'get').mockResolvedValue(uri);
  const data = structuredClone(comparison.mock);
  const module = data.modules.find(module => module.type === 'image')!;
  if (module.type === 'image') module.before.url = 'https://example.com/before.png';
  const result = await renderer.render({
    template: 'comparison',
    data,
    format: 'png',
    watermark: 'Generated by Forma',
  });
  expect(result.width).toBe(1200);
  expect(result.height).toBeGreaterThan(700);
  expect(result.warnings).toEqual([]);
  const png = PNG.sync.read(Buffer.from(result.body));
  let redPixels = 0;
  for (let i = 0; i < png.data.length; i += 4)
    if (Math.abs(png.data[i]! - 220) < 5 && Math.abs(png.data[i + 1]! - 30) < 5) redPixels++;
  expect(redPixels).toBeGreaterThan(20000);
  await mkdir('artifacts/comparison', { recursive: true });
  await writeFile('artifacts/comparison/preview.png', result.body);
  const svg = await renderer.render({ template: 'comparison', data, format: 'svg' });
  expect(Buffer.from(svg.body).toString()).toContain('<svg');
});
it('renders empty modules, long multilingual text and failed image fallback', async () => {
  vi.spyOn(ImageStore.prototype, 'get').mockRejectedValue(new Error('Image unavailable'));
  const result = await renderer.render({
    template: 'comparison',
    format: 'png',
    data: {
      title: '数据对比',
      modules: [
        { type: 'metric', items: [] },
        { type: 'entity', items: [] },
        { type: 'diff', before: '', after: '' },
        { type: 'text', before: '多语言 中文 日本語 English '.repeat(20), after: 'LongUnbrokenText'.repeat(30) },
        { type: 'image', before: { url: 'https://example.com/missing.png' }, after: { url: '' } },
      ],
    },
  });
  expect(result.warnings).toEqual(['IMAGE_UNAVAILABLE']);
  expect(PNG.sync.read(Buffer.from(result.body)).width).toBe(1200);
});
