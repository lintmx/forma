import { resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
import { build } from 'esbuild';
import { afterAll, beforeAll, describe, expect, it } from 'vitest';
import { buildOptions } from '../scripts/build-options.js';
import { createApp } from '../src/api/app.js';
import { loadConfig } from '../src/config.js';
import { RenderPool } from '../src/core/pool.js';
import { createTemplateRegistry } from '../src/templates/index.js';

const registry = createTemplateRegistry();
const config = loadConfig({ LOG_LEVEL: 'silent', RENDER_CONCURRENCY: '1', NODE_ENV: 'production' });
let pool: RenderPool;

beforeAll(async () => {
  await build({
    ...buildOptions,
    entryPoints: ['src/worker.ts'],
    outfile: '.dev/templates-test-worker.js',
  });
  pool = new RenderPool(config, pathToFileURL(resolve('.dev/templates-test-worker.js')));
  await pool.start();
});
afterAll(async () => {
  await pool?.close();
});

describe('production template catalog', () => {
  it('returns missing text and emoji placeholders with warnings through the real worker', async () => {
    const app = createApp(config, pool, registry);
    for (const format of ['svg', 'png']) {
      const response = await app.fetch(
        new Request('http://localhost/v1/render', {
          method: 'POST',
          headers: { 'Content-Type': 'application/json' },
          body: JSON.stringify({
            template: 'example',
            format,
            data: { text: '中文 💕︎ 🫸🏽 🧑🏽‍🩰 🫪 😀‍🚀 😀‍🚀 \u{10ffff} \u{10fffe}' },
          }),
        }),
      );
      expect(response.status).toBe(200);
      expect(response.headers.get('X-Render-Warnings')).toBe('EMOJI_UNAVAILABLE,MISSING_GLYPH');
      const body = Buffer.from(await response.arrayBuffer());
      if (format === 'svg') expect(body.toString().match(/<image\b/g)).toHaveLength(6);
      else expect(body.subarray(1, 4).toString()).toBe('PNG');
    }
    const clean = await pool.render({ template: 'example', data: { text: '💕︎ 🫪' }, format: 'svg' });
    expect(clean.warnings).toEqual([]);
  });

  it('starts real workers and serves example as the default template', async () => {
    expect(registry.list().map(template => template.id)).toEqual([
      'example',
      'social_post',
      'comparison',
      'article',
      'bilibili',
      'youtube',
    ]);
    const app = createApp(config, pool, registry);
    const health = await app.fetch(new Request('http://localhost/healthz'));
    expect(health.status).toBe(200);
    expect(await health.json()).toMatchObject({ status: 'ok', workers: 1 });
    const list = await app.fetch(new Request('http://localhost/v1/templates'));
    expect(list.status).toBe(200);
    const { templates } = await list.json();
    expect(templates.map((template: { id: string }) => template.id)).toEqual([
      'example',
      'social_post',
      'comparison',
      'article',
      'bilibili',
      'youtube',
    ]);
    const metadata = await app.fetch(new Request('http://localhost/v1/templates/example'));
    expect(metadata.status).toBe(200);
    const data = await metadata.json();
    expect(data.schema.required).toEqual(['text']);
    expect(Object.keys(data.schema.properties)).toEqual(['text', 'monospace']);
    expect(data.mock).toEqual(registry.get('example').mock);
  });

  it('exposes the social_post schema and renders it through a real worker', async () => {
    const app = createApp(config, pool, registry);
    const metadata = await app.fetch(new Request('http://localhost/v1/templates/social_post'));
    expect(metadata.status).toBe(200);
    const info = await metadata.json();
    expect(info.sizing).toEqual({ mode: 'content', minWidth: 400, maxWidth: 700 });
    expect(info.schema.properties).toHaveProperty('quotedPost');
    expect(info.schema.properties).not.toHaveProperty('schemaVersion');
    expect(info.schema.properties).not.toHaveProperty('watermark');
    expect(info.mock).toEqual(registry.get('social_post').mock);
    expect(info).not.toHaveProperty('documentation');
    for (const format of ['png', 'svg']) {
      const response = await app.fetch(
        new Request('http://localhost/v1/render', {
          method: 'POST',
          headers: { 'Content-Type': 'application/json' },
          body: JSON.stringify({ template: 'social_post', data: info.mock, format, watermark: 'Generated by Forma' }),
        }),
      );
      expect(response.status).toBe(200);
      expect(response.headers.get('Content-Type')).toContain(format === 'png' ? 'image/png' : 'image/svg+xml');
      expect(Number(response.headers.get('X-Image-Width'))).toBeGreaterThanOrEqual(format === 'png' ? 800 : 400);
      expect(Number(response.headers.get('X-Image-Width'))).toBeLessThanOrEqual(format === 'png' ? 1400 : 700);
      const body = Buffer.from(await response.arrayBuffer());
      expect(format === 'png' ? body.subarray(1, 4).toString() : body.toString().slice(0, 4)).toBe(
        format === 'png' ? 'PNG' : '<svg',
      );
    }
  });

  it('serves comparison metadata and renders through the production worker', async () => {
    const app = createApp(config, pool, registry);
    const metadata = await app.fetch(new Request('http://localhost/v1/templates/comparison'));
    expect(metadata.status).toBe(200);
    const info = await metadata.json();
    expect(info.schema.properties).toHaveProperty('modules');
    expect(info.schema.properties).not.toHaveProperty('watermark');
    const response = await app.fetch(
      new Request('http://localhost/v1/render', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({ template: 'comparison', data: info.mock, format: 'png' }),
      }),
    );
    expect(response.status).toBe(200);
    expect(response.headers.get('X-Image-Width')).toBe('1200');
    expect(
      Buffer.from(await response.arrayBuffer())
        .subarray(1, 4)
        .toString(),
    ).toBe('PNG');
  });

  it('exposes article with only content required and renders both formats through the production worker', async () => {
    const app = createApp(config, pool, registry);
    const metadata = await app.fetch(new Request('http://localhost/v1/templates/article'));
    expect(metadata.status).toBe(200);
    const info = await metadata.json();
    expect(info.schema.required).toEqual(['content']);
    expect(info.schema.properties).toHaveProperty('authorAvatarUrl');
    expect(info.schema.properties.translation.required ?? []).toEqual([]);
    expect(info.mock).toEqual(registry.get('article').mock);
    for (const format of ['png', 'svg']) {
      const response = await app.fetch(
        new Request('http://localhost/v1/render', {
          method: 'POST',
          headers: { 'Content-Type': 'application/json' },
          body: JSON.stringify({ template: 'article', data: info.mock, format }),
        }),
      );
      expect(response.status).toBe(200);
      expect(response.headers.get('Content-Type')).toContain(format === 'png' ? 'image/png' : 'image/svg+xml');
      expect(response.headers.get('X-Image-Width')).toBe(format === 'png' ? '1400' : '700');
      const body = Buffer.from(await response.arrayBuffer());
      expect(format === 'png' ? body.subarray(1, 4).toString() : body.toString().slice(0, 4)).toBe(
        format === 'png' ? 'PNG' : '<svg',
      );
    }
    const invalid = await app.fetch(
      new Request('http://localhost/v1/render', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({ template: 'article', data: { title: '缺少正文' } }),
      }),
    );
    expect(invalid.status).toBe(400);
    expect((await invalid.json()).error.code).toBe('VALIDATION_ERROR');
  });

  it('exposes bilibili metadata and renders video and live cards through the production worker', async () => {
    const app = createApp(config, pool, registry);
    const metadata = await app.fetch(new Request('http://localhost/v1/templates/bilibili'));
    expect(metadata.status).toBe(200);
    const info = await metadata.json();
    expect(info.schema.required).toEqual(['title']);
    expect(info.mock).toEqual(registry.get('bilibili').mock);
    for (const type of ['video', 'live']) {
      for (const format of ['png', 'svg']) {
        const response = await app.fetch(
          new Request('http://localhost/v1/render', {
            method: 'POST',
            headers: { 'Content-Type': 'application/json' },
            body: JSON.stringify({
              template: 'bilibili',
              format,
              data: {
                type,
                title: 'Bilibili 视频与直播',
                author: { name: '测试作者', uid: 123, verified: true },
                bvid: 'BV1W44y1G7u2',
                stats: { views: 0 },
                live: { status: 'live', roomId: 2289410, popularity: 1842000, startedAt: '20:15' },
              },
            }),
          }),
        );
        expect(response.status).toBe(200);
        expect(response.headers.get('X-Image-Width')).toBe(format === 'png' ? '1200' : '600');
        const body = Buffer.from(await response.arrayBuffer());
        expect(format === 'png' ? body.subarray(1, 4).toString() : body.toString().slice(0, 4)).toBe(
          format === 'png' ? 'PNG' : '<svg',
        );
      }
    }
  });

  it('exposes youtube metadata and renders API-shaped video and live data through the production worker', async () => {
    const app = createApp(config, pool, registry);
    const metadata = await app.fetch(new Request('http://localhost/v1/templates/youtube'));
    expect(metadata.status).toBe(200);
    const info = await metadata.json();
    expect(info.schema.required).toEqual(['snippet']);
    expect(info.schema.properties.snippet.required).toEqual(['title']);
    expect(info.mock).toEqual(registry.get('youtube').mock);
    const phases = [
      { snippet: { title: '已发布' }, statistics: { viewCount: '0' } },
      { snippet: { title: '定时发布' }, status: { privacyStatus: 'private', publishAt: '2026-10-25T12:00:00Z' } },
      {
        snippet: { title: '预约直播', liveBroadcastContent: 'upcoming' },
        liveStreamingDetails: { scheduledStartTime: '2026-10-22T12:00:00Z' },
      },
      {
        snippet: { title: '正在直播', liveBroadcastContent: 'live' },
        liveStreamingDetails: { actualStartTime: '2026-10-22T12:00:00Z', concurrentViewers: '1200' },
      },
      { snippet: { title: '直播结束' }, liveStreamingDetails: { actualEndTime: '2026-10-22T14:00:00Z' } },
      {
        snippet: { title: '回放' },
        liveStreamingDetails: { actualEndTime: '2026-10-22T14:00:00Z' },
        replayAvailable: true,
      },
    ];
    for (const format of ['png', 'svg']) {
      for (const data of phases) {
        const response = await app.fetch(
          new Request('http://localhost/v1/render', {
            method: 'POST',
            headers: { 'Content-Type': 'application/json' },
            body: JSON.stringify({ template: 'youtube', format, data }),
          }),
        );
        expect(response.status).toBe(200);
        expect(response.headers.get('X-Image-Width')).toBe(format === 'png' ? '1200' : '600');
        const body = Buffer.from(await response.arrayBuffer());
        expect(format === 'png' ? body.subarray(1, 4).toString() : body.toString().slice(0, 4)).toBe(
          format === 'png' ? 'PNG' : '<svg',
        );
      }
    }
  });

  it('renders body and Maple monospace text through the production worker', async () => {
    const app = createApp(config, pool, registry);
    const images = [];
    for (const monospace of [false, true]) {
      const response = await app.fetch(
        new Request('http://localhost/v1/render', {
          method: 'POST',
          headers: { 'Content-Type': 'application/json' },
          body: JSON.stringify({
            template: 'example',
            data: { text: 'iiii WWWW 中文 繁體 日本語 한국어 㐀㐁 ⏻', monospace },
            format: 'svg',
          }),
        }),
      );
      expect(response.status).toBe(200);
      images.push(await response.text());
    }
    expect(images[0]).not.toBe(images[1]);
  });

  it.each(['notice', 'profile', 'test-content', 'test-auto-height'])(
    'does not expose or render the unregistered template %s',
    async template => {
      const app = createApp(config, pool, registry);
      const metadata = await app.fetch(new Request('http://localhost/v1/templates/' + template));
      expect(metadata.status).toBe(404);
      expect((await metadata.json()).error.code).toBe('TEMPLATE_NOT_FOUND');
      const response = await app.fetch(
        new Request('http://localhost/v1/render', {
          method: 'POST',
          headers: { 'Content-Type': 'application/json' },
          body: JSON.stringify({ template, data: {} }),
        }),
      );
      expect(response.status).toBe(404);
      expect((await response.json()).error.code).toBe('TEMPLATE_NOT_FOUND');
      await expect(pool.render({ template, data: {}, format: 'svg' })).rejects.toMatchObject({
        code: 'TEMPLATE_NOT_FOUND',
        status: 404,
      });
      expect(pool.healthy).toBe(true);
    },
  );
});
