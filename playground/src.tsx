import { useEffect, useRef, useState } from "react";
import { createRoot } from "react-dom/client";
import "./style.css";

interface TemplateMetadata {
  id: string;
  name: string;
  description: string;
  mock: unknown;
  sizing: { mode: string };
  schema: unknown;
}
interface Preview {
  url: string;
  width: number;
  height: number;
  layoutWidth: number;
  layoutHeight: number;
  scale: number;
  elapsed: number;
  warnings: string;
  source: string;
}
function message(error: unknown) {
  return error instanceof Error ? error.message : String(error);
}
async function render(
  template: string,
  data: unknown,
  format: "png" | "svg",
  scale: number,
  watermark: string,
) {
  const response = await fetch("/v1/render", {
    method: "POST",
    headers: { "Content-Type": "application/json" },
    body: JSON.stringify({
      template,
      data,
      format,
      scale: format === "png" ? scale : 1,
      watermark,
    }),
  });
  if (!response.ok) {
    const body = await response.json();
    const details = Array.isArray(body.error?.details)
      ? body.error.details
          .map(
            (issue: { path: (string | number)[]; message: string }) =>
              (issue.path.join(".") || "data") + ": " + issue.message,
          )
          .join("\n")
      : "";
    throw new Error(
      (body.error?.message ?? "渲染失败") + (details ? "\n" + details : ""),
    );
  }
  return response;
}
function App() {
  const [templates, setTemplates] = useState<TemplateMetadata[]>([]);
  const [templatesLoading, setTemplatesLoading] = useState(true);
  const [selected, setSelected] = useState("");
  const [scale, setScale] = useState(2);
  const [watermark, setWatermark] = useState("Generated by Forma");
  const [json, setJson] = useState("");
  const [preview, setPreview] = useState<Preview>();
  const [error, setError] = useState("");
  const [loading, setLoading] = useState(false);
  const [downloading, setDownloading] = useState(false);
  const [showSchema, setShowSchema] = useState(false);
  const urlRef = useRef<string | undefined>(undefined);
  const template = templates.find((t) => t.id === selected);
  const source = JSON.stringify([selected, scale, watermark, json]);
  const fresh = !!template && preview?.source === source;

  useEffect(() => {
    let active = true;
    fetch("/v1/templates")
      .then(async (response) => {
        if (!response.ok) throw new Error("无法加载模板列表");
        const data = await response.json();
        if (active) {
          setTemplates(data.templates);
          setSelected(data.templates[0]?.id ?? "");
          setJson(JSON.stringify(data.templates[0]?.mock ?? {}, null, 2));
        }
      })
      .catch((error) => {
        if (active) setError(message(error));
      })
      .finally(() => {
        if (active) setTemplatesLoading(false);
      });
    return () => {
      active = false;
    };
  }, []);
  useEffect(() => {
    if (!template) return;
    let active = true;
    setLoading(true);
    setError("");
    const timer = setTimeout(async () => {
      try {
        const data = JSON.parse(json);
        const start = performance.now();
        const response = await render(selected, data, "png", scale, watermark);
        const blob = await response.blob();
        if (!active) return;
        const url = URL.createObjectURL(blob);
        if (urlRef.current) URL.revokeObjectURL(urlRef.current);
        urlRef.current = url;
        setPreview({
          url,
          width: Number(response.headers.get("X-Image-Width")),
          height: Number(response.headers.get("X-Image-Height")),
          layoutWidth: Number(response.headers.get("X-Layout-Width")),
          layoutHeight: Number(response.headers.get("X-Layout-Height")),
          scale: Number(response.headers.get("X-Render-Scale")),
          elapsed: Math.round(performance.now() - start),
          warnings: response.headers.get("X-Render-Warnings") ?? "",
          source,
        });
      } catch (error) {
        if (active) setError(message(error));
      } finally {
        if (active) setLoading(false);
      }
    }, 550);
    // Ignore outdated responses; do not repeatedly kill busy render workers.
    return () => {
      active = false;
      clearTimeout(timer);
    };
  }, [json, selected, scale, watermark, source, template]);
  useEffect(
    () => () => {
      if (urlRef.current) URL.revokeObjectURL(urlRef.current);
    },
    [],
  );
  function choose(id: string) {
    setSelected(id);
    setJson(
      JSON.stringify(templates.find((t) => t.id === id)?.mock ?? {}, null, 2),
    );
    setShowSchema(false);
  }
  async function download(format: "png" | "svg") {
    if (!template) return;
    setDownloading(true);
    try {
      const response = await render(
        selected,
        JSON.parse(json),
        format,
        scale,
        watermark,
      );
      const url = URL.createObjectURL(await response.blob());
      const anchor = document.createElement("a");
      anchor.href = url;
      anchor.download =
        selected + (format === "png" ? "@" + scale + "x" : "") + "." + format;
      anchor.click();
      setTimeout(() => URL.revokeObjectURL(url), 1000);
    } catch (error) {
      setError(message(error));
    } finally {
      setDownloading(false);
    }
  }
  return (
    <div className="app">
      <header className="header">
        <a href="/dev/" className="brand">
          <span className="brand-mark">f</span>forma
          <span className="version">PLAYGROUND / 01</span>
        </a>
        <div className="header-note">
          <span className="status-dot" /> Satori + resvg
        </div>
      </header>
      <main>
        <section className="intro">
          <div className="eyebrow">MESSAGES, BEAUTIFULLY FORMED</div>
          <h1>让信息，有自己的形状。</h1>
          <p>选择模板，填入内容。每一次预览，都是真正的图片输出。</p>
        </section>
        <div className="workspace">
          <section className="editor-panel" aria-label="卡片编辑器">
            <div className="panel-heading">
              <span className="step">01</span>
              <h2>内容与模板</h2>
            </div>
            <label className="field-label" htmlFor="template">
              卡片模板
            </label>
            <select
              id="template"
              value={selected}
              onChange={(e) => choose(e.target.value)}
              disabled={templates.length === 0}
            >
              {templates.length === 0 && (
                <option value="">
                  {templatesLoading ? "正在加载模板…" : "暂无可用模板"}
                </option>
              )}
              {templates.map((t) => (
                <option value={t.id} key={t.id}>
                  {t.name} / {t.id}
                </option>
              ))}
            </select>
            <p className="template-description">
              {template?.description ??
                (!templatesLoading && !error
                  ? "注册模板后即可编辑内容并预览。"
                  : "")}
            </p>
            <label className="field-label" htmlFor="scale">
              PNG 清晰度
            </label>
            <select
              id="scale"
              value={scale}
              onChange={(e) => setScale(Number(e.target.value))}
              disabled={!template}
            >
              <option value={1}>1× · 标准</option>
              <option value={2}>2× · 高清（推荐）</option>
              <option value={3}>3× · 超清</option>
              <option value={4}>4× · 精细</option>
            </select>
            <div className="watermark-field">
              <label className="field-label" htmlFor="watermark">
                底部水印
              </label>
              <input
                id="watermark"
                type="text"
                maxLength={160}
                value={watermark}
                onChange={(e) => setWatermark(e.target.value)}
                placeholder="留空隐藏水印"
                disabled={!template}
              />
            </div>
            <div className="editor-toolbar">
              <label htmlFor="json">JSON DATA</label>
              <button
                disabled={!template}
                onClick={() =>
                  setJson(JSON.stringify(template?.mock ?? {}, null, 2))
                }
              >
                恢复示例
              </button>
            </div>
            <textarea
              id="json"
              spellCheck={false}
              value={json}
              onChange={(e) => setJson(e.target.value)}
              aria-describedby={error ? "error" : undefined}
              disabled={!template}
            />
            {error && (
              <pre id="error" className="error" role="alert">
                {error}
              </pre>
            )}
            <div className="editor-footer">
              <button
                disabled={!template}
                onClick={() => setShowSchema(!showSchema)}
              >
                {showSchema ? "收起 Schema" : "查看 Schema"}
              </button>
            </div>
            {showSchema && template && (
              <pre className="schema">
                {JSON.stringify(template?.schema, null, 2)}
              </pre>
            )}
          </section>
          <section className="preview-panel" aria-label="图片预览">
            <div className="panel-heading">
              <span className="step">02</span>
              <h2>图片预览</h2>
              <span
                className={"render-status " + (error ? "invalid" : "")}
                aria-live="polite"
              >
                {templatesLoading
                  ? "加载模板中…"
                  : loading
                    ? "渲染中…"
                    : error
                      ? template
                        ? "请检查输入"
                        : "模板加载失败"
                      : !template
                        ? "暂无模板"
                        : fresh
                          ? "已更新"
                          : "等待预览"}
              </span>
            </div>
            <div className="preview-stage">
              {preview ? (
                <img
                  src={preview.url}
                  width={preview.layoutWidth}
                  height={preview.layoutHeight}
                  alt={template?.name + "真实 PNG 预览"}
                  className={!fresh ? "stale" : ""}
                />
              ) : (
                <div className="placeholder">
                  {templatesLoading
                    ? "正在加载模板…"
                    : template
                      ? "你的下一张卡片，从这里开始。"
                      : error
                        ? "暂时无法加载模板。"
                        : "暂无可用模板，注册后即可预览。"}
                </div>
              )}
              {preview && !fresh && (
                <span className="stale-label">上一次成功预览</span>
              )}
            </div>
            <div className="preview-footer">
              <span>
                {preview
                  ? preview.width +
                    " × " +
                    preview.height +
                    " px · " +
                    preview.scale +
                    "× · " +
                    preview.elapsed +
                    " ms"
                  : "等待生成"}
              </span>
              <span>{template?.sizing.mode}</span>
            </div>
            {preview?.warnings && (
              <div className="warning">
                图片资源加载失败，已使用模板的降级内容。
              </div>
            )}
            <div className="downloads">
              <button
                className="secondary"
                disabled={!fresh || !!error || downloading}
                onClick={() => void download("svg")}
              >
                下载 SVG
              </button>
              <button
                className="primary"
                disabled={!fresh || !!error || downloading}
                onClick={() => void download("png")}
              >
                下载 PNG <span>↓</span>
              </button>
            </div>
          </section>
        </div>
        <footer className="page-footer">
          <span>FORMA / SCHEMA-DRIVEN CARDS</span>
          <span>中 · 日 · EN &nbsp; / &nbsp; 同一管线，一致输出</span>
        </footer>
      </main>
    </div>
  );
}
createRoot(document.getElementById("root")!).render(<App />);
