import { useEffect, useRef, useState } from 'react';
import { createRoot } from 'react-dom/client';
import { render, renderWarningMessage, type TemplateMetadata } from './api.js';
import './style.css';

interface Preview {
  url: string;
  width: number;
  height: number;
  layoutWidth: number;
  layoutHeight: number;
  scale: number;
  elapsed: number;
  bytes: number;
  warnings: string;
  source: string;
}
function formatBytes(bytes: number) {
  if (bytes < 1024) return bytes + ' B';
  if (bytes < 1024 * 1024) return (bytes / 1024).toFixed(1) + ' KiB';
  return (bytes / (1024 * 1024)).toFixed(2) + ' MiB';
}
function message(error: unknown) {
  return error instanceof Error ? error.message : String(error);
}
function presetDraft(preset: TemplateMetadata['presets'][number]) {
  return {
    json: JSON.stringify(preset.data, null, 2),
    watermark: preset.watermark ?? 'Generated by Forma',
    assetUrlPrefix: preset.assetUrlPrefix ?? '',
  };
}
function App() {
  const [templates, setTemplates] = useState<TemplateMetadata[]>([]);
  const [templatesLoading, setTemplatesLoading] = useState(true);
  const [selected, setSelected] = useState('');
  const [presetId, setPresetId] = useState('default');
  const [watermark, setWatermark] = useState('Generated by Forma');
  const [assetUrlPrefix, setAssetUrlPrefix] = useState('');
  const [json, setJson] = useState('');
  const [preview, setPreview] = useState<Preview>();
  const [error, setError] = useState('');
  const [loading, setLoading] = useState(false);
  const [downloading, setDownloading] = useState<'png' | 'svg' | null>(null);
  const [showSchema, setShowSchema] = useState(false);
  const urlRef = useRef<string | undefined>(undefined);
  const drafts = useRef(new Map<string, ReturnType<typeof presetDraft>>());
  const lastPresets = useRef(new Map<string, string>());
  const template = templates.find(t => t.id === selected);
  const preset = template?.presets.find(p => p.id === presetId);
  const original = preset && presetDraft(preset);
  const modified =
    !!original &&
    (json !== original.json || watermark !== original.watermark || assetUrlPrefix !== original.assetUrlPrefix);
  const source = JSON.stringify([selected, presetId, watermark, assetUrlPrefix, json]);
  const fresh = !!template && preview?.source === source;

  useEffect(() => {
    let active = true;
    fetch('/v1/templates')
      .then(async response => {
        if (!response.ok) throw new Error('无法加载模板列表');
        const data = await response.json();
        if (active) {
          setTemplates(data.templates);
          setSelected(data.templates[0]?.id ?? '');
          setJson(JSON.stringify(data.templates[0]?.mock ?? {}, null, 2));
        }
      })
      .catch(error => {
        if (active) setError(message(error));
      })
      .finally(() => {
        if (active) setTemplatesLoading(false);
      });
    return () => {
      active = false;
    };
  }, []);
  useEffect(() => {
    if (!template) return;
    let active = true;
    setLoading(true);
    setError('');
    const timer = setTimeout(async () => {
      try {
        const data = JSON.parse(json);
        const start = performance.now();
        const response = await render({ template: selected, data, format: 'png', watermark, assetUrlPrefix });
        const blob = await response.blob();
        if (!active) return;
        const url = URL.createObjectURL(blob);
        if (urlRef.current) URL.revokeObjectURL(urlRef.current);
        urlRef.current = url;
        setPreview({
          url,
          bytes: blob.size,
          width: Number(response.headers.get('X-Image-Width')),
          height: Number(response.headers.get('X-Image-Height')),
          layoutWidth: Number(response.headers.get('X-Layout-Width')),
          layoutHeight: Number(response.headers.get('X-Layout-Height')),
          scale: Number(response.headers.get('X-Render-Scale')),
          elapsed: Math.round(performance.now() - start),
          warnings: response.headers.get('X-Render-Warnings') ?? '',
          source,
        });
      } catch (error) {
        if (active) setError(message(error));
      } finally {
        if (active) setLoading(false);
      }
    }, 550);
    // Ignore outdated responses; do not repeatedly kill busy render workers.
    return () => {
      active = false;
      clearTimeout(timer);
    };
  }, [json, selected, watermark, assetUrlPrefix, source, template]);
  useEffect(
    () => () => {
      if (urlRef.current) URL.revokeObjectURL(urlRef.current);
    },
    [],
  );
  function applyDraft(draft: ReturnType<typeof presetDraft>) {
    setJson(draft.json);
    setWatermark(draft.watermark);
    setAssetUrlPrefix(draft.assetUrlPrefix);
  }
  function choose(id: string, nextPresetId = lastPresets.current.get(id) ?? 'default') {
    const nextPreset = templates.find(t => t.id === id)!.presets.find(p => p.id === nextPresetId)!;
    drafts.current.set(selected + '/' + presetId, { json, watermark, assetUrlPrefix });
    lastPresets.current.set(id, nextPresetId);
    setSelected(id);
    setPresetId(nextPresetId);
    applyDraft(drafts.current.get(id + '/' + nextPresetId) ?? presetDraft(nextPreset));
    setShowSchema(false);
  }
  function resetPreset() {
    if (!original) return;
    drafts.current.delete(selected + '/' + presetId);
    applyDraft(original);
  }
  async function download(format: 'png' | 'svg') {
    if (!template) return;
    setDownloading(format);
    try {
      const response = await render({ template: selected, data: JSON.parse(json), format, watermark, assetUrlPrefix });
      const url = URL.createObjectURL(await response.blob());
      const anchor = document.createElement('a');
      anchor.href = url;
      anchor.download = selected + '-' + presetId + (format === 'png' ? '@2x' : '') + '.' + format;
      anchor.click();
      setTimeout(() => URL.revokeObjectURL(url), 1000);
    } catch (error) {
      setError(message(error));
    } finally {
      setDownloading(null);
    }
  }
  return (
    <div className="app">
      <header className="header">
        <a href="/" className="brand" aria-label="Forma 首页">
          <span className="brand-mark" aria-hidden="true">
            f
          </span>
          forma
        </a>
        <nav aria-label="主导航">
          <a href="/">概览</a>
          <a href="/dev/" aria-current="page">
            Playground{' '}
            <span className="nav-arrow" aria-hidden="true">
              ↗
            </span>
          </a>
        </nav>
      </header>
      <main>
        <section className="intro">
          <div>
            <div className="eyebrow">THE PLAYGROUND</div>
            <h1>让想法，在这里成形。</h1>
          </div>
          <p>
            选择模板，写下内容。
            <br />
            下一张好图片，从这里开始。
          </p>
        </section>
        <div className="workspace">
          <section className="editor-panel" aria-label="卡片编辑器">
            <div className="panel-heading">
              <span className="step">01</span>
              <h2>内容与模板</h2>
              <a className="preview-jump" href="#preview">
                查看预览 ↓
              </a>
            </div>
            <label className="field-label" htmlFor="template">
              卡片模板
            </label>
            <select
              id="template"
              value={selected}
              onChange={e => choose(e.target.value)}
              disabled={templates.length === 0}
            >
              {templates.length === 0 && (
                <option value="">{templatesLoading ? '正在加载模板…' : '暂无可用模板'}</option>
              )}
              {templates.map(t => (
                <option value={t.id} key={t.id}>
                  {t.name} / {t.id}
                </option>
              ))}
            </select>
            <p className="template-description">
              {template?.description ?? (!templatesLoading && !error ? '注册模板后即可编辑内容并预览。' : '')}
            </p>
            <label className="field-label" htmlFor="preset">
              预设配置
            </label>
            <select id="preset" value={presetId} onChange={e => choose(selected, e.target.value)} disabled={!template}>
              {!template && <option value="default">暂无预设</option>}
              {template?.presets.map(p => (
                <option value={p.id} key={p.id}>
                  {p.name}
                </option>
              ))}
            </select>
            <div className="editor-toolbar">
              <label htmlFor="json">
                data.json
                {modified && (
                  <span className="modified" role="status">
                    {' '}
                    / 已修改
                  </span>
                )}
              </label>
              <button type="button" disabled={!template} onClick={resetPreset}>
                重置当前预设
              </button>
            </div>
            <textarea
              id="json"
              spellCheck={false}
              value={json}
              onChange={e => setJson(e.target.value)}
              aria-describedby={error ? 'error' : undefined}
              disabled={!template}
            />
            {error && (
              <pre id="error" className="error" role="alert">
                {error}
              </pre>
            )}
            <details className="export-options">
              <summary>
                输出设置 <span className="options-hint">水印与图片资源</span>
              </summary>
              <div className="watermark-field">
                <label className="field-label" htmlFor="watermark">
                  底部水印
                </label>
                <input
                  id="watermark"
                  type="text"
                  maxLength={160}
                  value={watermark}
                  onChange={e => setWatermark(e.target.value)}
                  placeholder="留空隐藏水印"
                  disabled={!template}
                />
              </div>
              <div className="watermark-field">
                <label className="field-label" htmlFor="asset-url-prefix">
                  资源 URL 前缀
                </label>
                <input
                  id="asset-url-prefix"
                  type="url"
                  maxLength={2048}
                  value={assetUrlPrefix}
                  onChange={e => setAssetUrlPrefix(e.target.value)}
                  placeholder="例如 http://localhost:8000/，留空不补全"
                  disabled={!template}
                />
              </div>
            </details>
            <div className="editor-footer">
              <span>JSON / UTF-8</span>
              <button
                type="button"
                disabled={!template}
                aria-expanded={showSchema}
                aria-controls="template-schema"
                onClick={() => setShowSchema(!showSchema)}
              >
                {showSchema ? '收起 Schema −' : '查看 Schema +'}
              </button>
            </div>
            {showSchema && template && (
              <pre id="template-schema" className="schema">
                {JSON.stringify(template.schema, null, 2)}
              </pre>
            )}
          </section>
          <section id="preview" className="preview-panel" aria-label="图片预览">
            <div className="preview-content">
              <div className="panel-heading">
                <span className="step">02</span>
                <h2>图片预览</h2>
                <span className={'render-status ' + (error ? 'invalid' : loading ? 'busy' : '')} aria-live="polite">
                  {templatesLoading
                    ? '加载模板中…'
                    : loading
                      ? '渲染中…'
                      : error
                        ? template
                          ? '请检查输入'
                          : '模板加载失败'
                        : !template
                          ? '暂无模板'
                          : fresh
                            ? '已更新'
                            : '等待预览'}
                </span>
              </div>
              <div className="preview-stage" aria-busy={loading}>
                <span className="canvas-label" aria-hidden="true">
                  OUTPUT / PNG
                </span>
                {preview ? (
                  <a
                    className="preview-image"
                    href={preview.url}
                    target="_blank"
                    rel="noreferrer"
                    aria-label="在新窗口查看原图"
                  >
                    <img
                      src={preview.url}
                      width={preview.layoutWidth}
                      height={preview.layoutHeight}
                      alt={template?.name + ' / ' + preset?.name + '真实 PNG 预览'}
                      className={!fresh ? 'stale' : ''}
                    />
                    <span className="image-action" aria-hidden="true">
                      查看原图 ↗
                    </span>
                  </a>
                ) : (
                  <div className="placeholder">
                    {templatesLoading
                      ? '正在加载模板…'
                      : template
                        ? '正在为内容排版…'
                        : error
                          ? '暂时无法加载模板。'
                          : '暂无可用模板，注册后即可预览。'}
                  </div>
                )}
                {preview && !fresh && <span className="stale-label">上一次成功预览</span>}
              </div>
              <div className="preview-footer">
                <span>
                  {preview
                    ? preview.width +
                      ' × ' +
                      preview.height +
                      ' px / ' +
                      preview.scale +
                      '× / ' +
                      preview.elapsed +
                      ' ms / ' +
                      formatBytes(preview.bytes)
                    : '等待生成'}
                </span>
                <span>PNG / 2×</span>
              </div>
              {preview?.warnings && <div className="warning">{renderWarningMessage(preview.warnings)}</div>}
              <div className="downloads">
                <button
                  type="button"
                  className="secondary"
                  disabled={!fresh || !!error || !!downloading}
                  onClick={() => void download('svg')}
                >
                  {downloading === 'svg' ? '正在导出…' : '下载 SVG'}
                </button>
                <button
                  type="button"
                  className="primary"
                  disabled={!fresh || !!error || !!downloading}
                  onClick={() => void download('png')}
                >
                  {downloading === 'png' ? '正在导出…' : '下载 PNG'}{' '}
                  <span className="download-arrow" aria-hidden="true">
                    ↓
                  </span>
                </button>
              </div>
              <p className="preview-note">点击图片查看原图。PNG 高清导出，SVG 保留矢量。</p>
            </div>
          </section>
        </div>
        <footer className="page-footer">
          <span>forma / 让内容有形</span>
          <span>STRUCTURED IN. BEAUTIFULLY OUT.</span>
        </footer>
      </main>
    </div>
  );
}
createRoot(document.getElementById('root')!).render(<App />);
